// ─── Core functions ───────────────────────────────────────────────────────────

function switchLanguage(lang) {
    if (!EUDORA_TRANSLATIONS[lang]) return;
    localStorage.setItem('eudora-lang', lang);
    applyEudoraTranslations(lang);
    updateLangButtons(lang);
    document.documentElement.lang = lang;
}

function applyEudoraTranslations(lang) {
    const t = EUDORA_TRANSLATIONS[lang];
    if (!t) return;

    // Text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (t[key] !== undefined) el.textContent = t[key];
    });

    // Placeholder attributes
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        if (t[key] !== undefined) el.placeholder = t[key];
    });
}

function updateLangButtons(lang) {
    document.querySelectorAll('.lang-btn').forEach(btn => {
        const isActive = btn.dataset.lang === lang;
        btn.classList.toggle('active', isActive);
    });
}

// ─── Init ─────────────────────────────────────────────────────────────────────

document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('eudora-lang') || 'it';
    switchLanguage(saved);
});
